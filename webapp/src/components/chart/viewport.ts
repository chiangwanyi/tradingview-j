import { reactive } from 'vue'

/**
 * 画布的**可视几何**（唯一的对外快照）。
 *
 * 为什么要把这几个数从 ChartPanel 里拿出来：横轴下方的录音条要**和 K 线严格对齐** ——
 * 一条语音挂在哪根 K 线上，它的小标记就该正好在那根柱子的正下方。对齐只有一种做法：
 * 用**同一个** barWidth / scroll / plot.left 算 x。让录音条自己再算一遍（比如按
 * 「时间 → 比例」去推）必然差半根：K 线的时间是不等距的（周末、休市、跳空），
 * 而横轴是**按下标**排的，只有画布自己知道当前是哪一段、缩放到了多少。
 *
 * 所以这里只是一份**只读快照**：ChartPanel 每次重绘前写一次，别的地方只读。
 * 不要往这里塞操作，也不要在这里存「谁选中了什么」—— 那是 store 的事。
 */
export const chartViewport = reactive({
  /** 画布宽度（= 录音条的宽度，两者同宽同源） */
  width: 0,
  /** 行情区左边界：时间轴的起点，也是第一根 K 线的中心线再往左半根 */
  left: 0,
  /** 行情区右边界：价格轴的左沿（右边那 86px 是价格刻度） */
  right: 0,
  /** 一根 K 线多少像素 */
  barWidth: 7,
  /** 左边缘对应的（分数）下标 */
  scroll: 0,
})

/**
 * 「把某一根 K 线移到视野中间」—— 由 ChartPanel 挂载时注册。
 *
 * 谁用得到：录音条两侧的 `‹n` / `n›`。语音可能在视野之外（复盘是往前走的，
 * 早先几根早就划出去了），没有这一步，那几条就只能靠人瞎拖去找。
 *
 * 默认实现是空的：录音条单独渲染（没有画布）时不至于报错。
 */
export const chartNav: { centerOn: (index: number) => void } = {
  centerOn: () => {},
}
